# Question 37: Write a program to check whether a number lies between 10 and 50.

num = int(input("Enter a number: "))

if 10 <= num <= 50:
    print(num, "lies between 10 and 50")
else:
    print(num, "does not lie between 10 and 50")


# ----- Output -----
# Enter a number: 32
# 32 lies between 10 and 50
