# Question 10: Write a program to check whether a number is a single-digit number or not.

num = int(input("Enter a number: "))

if -9 <= num <= 9:
    print("It is a single-digit number")
else:
    print("It is not a single-digit number")


# ----- Output -----
# Enter a number: 7
# It is a single-digit number
