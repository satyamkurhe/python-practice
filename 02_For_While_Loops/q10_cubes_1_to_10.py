# Question 10: Print cube of numbers from 1 to 10.

for i in range(1, 11):
    print("Cube of", i, "is", i ** 3)


# ----- Output -----
# Cube of 1 is 1
# Cube of 2 is 8
# Cube of 3 is 27
# Cube of 4 is 64
# Cube of 5 is 125
# Cube of 6 is 216
# Cube of 7 is 343
# Cube of 8 is 512
# Cube of 9 is 729
# Cube of 10 is 1000
