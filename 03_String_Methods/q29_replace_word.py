# Question 29: Replace a word with another word in a sentence.

sentence = input("Enter a sentence: ")
old = input("Enter the word to replace: ")
new = input("Enter the new word: ")

print("Updated sentence:", sentence.replace(old, new))


# ----- Output -----
# Enter a sentence: I like Java
# Enter the word to replace: Java
# Enter the new word: Python
# Updated sentence: I like Python
